<h2>Size or style exchange</h2>
<p>Children grow quickly and sizes can be tricky. You can exchange an item for a different size, or for another item of the same value, within <strong>7 days of delivery</strong>.</p>

<h2>Conditions</h2>
<ul>
    <li>The item must be unused and unwashed, with original tags and packaging.</li>
    <li>The size or item you want must be in stock. If it is not, we will offer a refund instead.</li>
</ul>

<h2>How to exchange</h2>
<ol>
    <li>Contact us at <a href="mailto:info@bloomkidswear.com">info@bloomkidswear.com</a> or <a href="tel:+923361010002">+92 336 1010002</a> with your order number and the size you need.</li>
    <li>We confirm availability and arrange pickup or tell you where to send the item.</li>
    <li>We dispatch the replacement once the original reaches us.</li>
</ol>

<h2>Delivery cost</h2>
<p>The first size exchange on an order is free if the item you received was faulty or incorrect. Otherwise the delivery charge for sending the replacement is paid by the customer.</p>

