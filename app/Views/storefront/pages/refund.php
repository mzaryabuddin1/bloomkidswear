<h2>Returns</h2>
<p>You can return an item within <strong>7 days of delivery</strong> if it is unused, unwashed and has its original tags and packaging.</p>

<h2>Items we cannot take back</h2>
<ul>
    <li>Items that are worn, washed, altered or damaged after delivery.</li>
    <li>Innerwear, socks and other hygiene items, and items marked final sale.</li>
</ul>

<h2>Damaged or wrong item</h2>
<p>If you receive a damaged, defective or incorrect item, contact us within 48 hours of delivery with your order number and a photo. We will replace it or refund you in full, including delivery.</p>

<h2>How to start a return</h2>
<p>Email <a href="mailto:info@bloomkidswear.com">info@bloomkidswear.com</a> or call <a href="tel:+923361010002">+92 336 1010002</a> with your order number. We will confirm the return and arrange pickup or tell you where to send it.</p>

<h2>Refunds</h2>
<p>Once the returned item is received and checked, we refund the item price within 7 working days. Card payments are refunded to the original card; cash on delivery orders are refunded by bank transfer to the account you give us.</p>

<h2>Cancelled orders</h2>
<p>If we cancel your order, any payment you made is refunded in full.</p>
