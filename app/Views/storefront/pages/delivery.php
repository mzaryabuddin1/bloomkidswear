<h2>Delivery time</h2>
<p>Orders are packed and handed to our courier after confirmation. Delivery usually takes 2–5 working days, depending on your city. Delays can happen during sales, holidays or bad weather.</p>

<h2>Cash on delivery</h2>
<p>If you choose cash on delivery, please keep the exact amount ready for the courier.</p>

<h2>Tracking</h2>
<p>We email you when your order is shipped, including the courier name and tracking number where available. You can also use our <a href="<?= site_url('track-order') ?>">Track Order</a> page.</p>

<h2>Incorrect address or missed delivery</h2>
<p>Please make sure your address and phone number are correct. If the courier cannot reach you, the order may be returned to us; contact us to arrange re-delivery.</p>
