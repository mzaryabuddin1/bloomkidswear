<p>Bloom Kidswear respects your privacy. This page explains what we collect and how we use it.</p>

<h2>Information we collect</h2>
<ul>
    <li>Account details: name, email, phone number and password (stored securely, never in plain text).</li>
    <li>Order details: delivery address, items ordered and payment method.</li>
    <li>Basic technical data such as cookies needed to keep you signed in and your cart working.</li>
</ul>

<h2>How we use it</h2>
<ul>
    <li>To process and deliver your orders and send order and status emails.</li>
    <li>To send verification codes when you sign up or reset your password.</li>
    <li>To provide customer support and improve our store.</li>
</ul>

<h2>Card payments</h2>
<p>We do not store your full card number or security code on our servers.</p>

<h2>Sharing</h2>
<p>We share your name, phone number and address with our delivery partners only so they can deliver your order. We do not sell your personal information.</p>

<h2>Your choices</h2>
<p>You can update or delete your account from the account pages, or contact us to have your data removed.</p>

